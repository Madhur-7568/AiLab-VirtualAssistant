"""
Healthcare LLM Integration Engine
Supports Google Gemini API, OpenAI API, and embedded clinical reasoning fallback.
"""

import os
import json
from typing import Dict, Any, List, Optional
import httpx
from src.healthcare.medical_knowledge import MedicalKnowledgeBase


class HealthcareLLMEngine:
    """
    Orchestrates LLM generation for Healthcare Virtual Assistant.
    """

    HEALTHCARE_SYSTEM_PROMPT = """You are HealthPulse AI, a professional, empathetic, and evidence-based Healthcare Virtual Assistant.
Your mission is to help users understand symptoms, clarify medical doubts, understand medications, and promote healthy lifestyles.

Clinical Guidelines to strictly follow:
1. Always maintain a warm, calm, empathetic, and professional clinical bedside manner.
2. Structure your answers with clear markdown headers, bullet points, and key takeaways.
3. If the user mentions any emergency symptoms (e.g. chest pressure, radiating arm pain, severe shortness of breath, sudden facial drooping or slurred speech, severe allergic reaction), immediately emphasize seeking emergency medical care (dial 911 / 112).
4. Provide practical self-care steps, hydration/nutrition advice, and over-the-counter options when appropriate.
5. Clarify potential causes without diagnosing conclusively. Use phrases like "Possible factors include..." or "Common causes can be...".
6. Always conclude with a clear indication of when to see a licensed physician.
7. Include the standard medical disclaimer at the bottom: 'Disclaimer: This information is for educational purposes and is not a substitute for professional medical advice, diagnosis, or treatment.'"""

    def __init__(self, api_key: Optional[str] = None, provider: str = "auto"):
        self.api_key = api_key or os.environ.get("GEMINI_API_KEY") or os.environ.get("OPENAI_API_KEY")
        self.provider = provider.lower()

    def generate_response(
        self,
        query: str,
        conversation_history: Optional[List[Dict[str, str]]] = None,
        api_key_override: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Generate response using configured LLM or fallback clinical knowledge engine.
        """
        active_key = api_key_override or self.api_key
        conversation_history = conversation_history or []

        # 1. First priority: Check for severe life-threatening emergency
        emergency = MedicalKnowledgeBase.check_emergency(query)
        if emergency:
            return {
                "response": MedicalKnowledgeBase.generate_expert_response(query),
                "model_used": "Emergency Triage Guardrail",
                "is_emergency": True,
                "disclaimer": "Emergency protocol triggered.",
            }

        # 2. Try Google Gemini API if key is available
        if active_key and (self.provider in ["auto", "gemini"] or active_key.startswith("AIza")):
            gemini_res = self._call_gemini(query, active_key, conversation_history)
            if gemini_res:
                return {
                    "response": gemini_res,
                    "model_used": "Google Gemini 1.5 Flash",
                    "is_emergency": False,
                    "disclaimer": "Generated by Google Gemini AI with Healthcare Safety Guardrails.",
                }

        # 3. Try OpenAI API if key is available
        if active_key and (self.provider in ["auto", "openai"] or active_key.startswith("sk-")):
            openai_res = self._call_openai(query, active_key, conversation_history)
            if openai_res:
                return {
                    "response": openai_res,
                    "model_used": "OpenAI GPT-4o-mini",
                    "is_emergency": False,
                    "disclaimer": "Generated by OpenAI with Healthcare Safety Guardrails.",
                }

        # 4. Embedded Clinical Expert Knowledge Engine (Guaranteed zero-dependency fallback)
        fallback_res = MedicalKnowledgeBase.generate_expert_response(query)
        return {
            "response": fallback_res,
            "model_used": "Clinical Expert Knowledge Engine",
            "is_emergency": False,
            "disclaimer": "Generated by Embedded Medical Knowledge Base (Connect Gemini API Key for live open-ended LLM)",
        }

    def _call_gemini(self, query: str, api_key: str, history: List[Dict[str, str]]) -> Optional[str]:
        """Call Google Gemini 1.5 Flash API via REST."""
        endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"

        contents = []
        for msg in history[-6:]:
            role = "user" if msg.get("role") == "user" else "model"
            contents.append({"role": role, "parts": [{"text": msg.get("content", "")}]})

        contents.append({"role": "user", "parts": [{"text": query}]})

        payload = {
            "contents": contents,
            "systemInstruction": {"parts": [{"text": self.HEALTHCARE_SYSTEM_PROMPT}]},
            "generationConfig": {
                "temperature": 0.4,
                "topP": 0.95,
                "maxOutputTokens": 1024,
            },
        }

        try:
            with httpx.Client(timeout=15.0) as client:
                resp = client.post(endpoint, json=payload)
                if resp.status_code == 200:
                    data = resp.json()
                    candidates = data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        if parts:
                            return parts[0].get("text", "")
        except Exception as e:
            print(f"[LLM Engine] Gemini API error: {e}")
        return None

    def _call_openai(self, query: str, api_key: str, history: List[Dict[str, str]]) -> Optional[str]:
        """Call OpenAI API via REST."""
        endpoint = "https://api.openai.com/v1/chat/completions"

        messages = [{"role": "system", "content": self.HEALTHCARE_SYSTEM_PROMPT}]
        for msg in history[-6:]:
            messages.append({"role": msg.get("role", "user"), "content": msg.get("content", "")})
        messages.append({"role": "user", "content": query})

        payload = {
            "model": "gpt-4o-mini",
            "messages": messages,
            "temperature": 0.4,
            "max_tokens": 1024,
        }

        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        }

        try:
            with httpx.Client(timeout=15.0) as client:
                resp = client.post(endpoint, json=payload, headers=headers)
                if resp.status_code == 200:
                    data = resp.json()
                    choices = data.get("choices", [])
                    if choices:
                        return choices[0].get("message", {}).get("content", "")
        except Exception as e:
            print(f"[LLM Engine] OpenAI API error: {e}")
        return None
